"""Kaggle GPU training kernel for the contrastive encoder (RESEARCH.md roadmap item 1).

Generates ``notebooks/kaggle_train_encoder.ipynb`` (do not edit it by hand), pushes it as a
PRIVATE GPU kernel (internet off) and fetches its outputs. Conventions follow
``scripts/package_kaggle.py`` (dataset discovery by slug, RDKit from the metric wheel
dataset) and ``scripts/kaggle_common.py`` (API, credentials through the proxy).

Datasets the kernel mounts (publish them first with ``scripts/kaggle_publish.py``)::

    python scripts/kaggle_publish.py --name casmi-encoder-code --src src/casmi=casmi \\
        --src scripts/train_encoder.py=scripts --message "encoder code <commit>"
    python scripts/kaggle_publish.py --name casmi-encoder-bundle \\
        --src data/processed/encoder/bundle_v1 --message "bundle v1"
    # plus the existing casmi-db-np (np_fp.npy) and metric/rdkit-2026-3-3-wheel

Subcommands::

    python scripts/kaggle_encoder_kernel.py notebook --arms bce focal_con --hours 4.5
    python scripts/kaggle_encoder_kernel.py push --arms bce focal_con --hours 4.5 [--wait --fetch]
    python scripts/kaggle_encoder_kernel.py status
    python scripts/kaggle_encoder_kernel.py fetch      # -> dist/kaggle/output/<slug>_<stamp>/

On a two-GPU machine (T4 x2) the arms train in parallel, one per GPU, each for ``--hours``;
with one GPU they run one after the other with ``--hours / n_arms`` each.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kaggle_common as kc  # noqa: E402
from package_kaggle import FIND_INPUT, _code, _md, _nb  # noqa: E402

ROOT = kc.ENV_ROOT
NOTEBOOK = ROOT / "notebooks" / "kaggle_train_encoder.ipynb"
SLUG = "casmi-encoder-train"
TITLE = "casmi encoder train"
CODE_DATASET = "casmi-encoder-code"
BUNDLE_DATASET = "casmi-encoder-bundle"
NP_DATASET = "casmi-db-np"


def notebook(owner: str, arms: list[str], hours: float, sets: dict, eval_max_mol: int,
             commit: str) -> dict:
    settings = f'''
# ---- settings (generated by scripts/kaggle_encoder_kernel.py at {commit}) ----
from pathlib import Path
OWNER = {owner!r}
ARMS = {arms!r}                  # casmi.encoder.ARMS keys, one GPU each when possible
HOURS = {hours!r}                # training wall budget per arm (parallel case)
SETS = {json.dumps(sets, sort_keys=True)}       # Config overrides for every arm (--set key=value)
EVAL_MAX_MOL = {eval_max_mol!r}  # 0 = full NP-TIMS / NP-OTHER evaluation packs
CODE_DATASET = {CODE_DATASET!r}
BUNDLE_DATASET = {BUNDLE_DATASET!r}
NP_DATASET = {NP_DATASET!r}
RDKIT_WHEEL_DATASET = {kc.RDKIT_WHEEL_DATASET!r}
WORK = Path("/kaggle/working")
OUT = WORK / "encoder"
'''
    setup = r'''
T0 = time.time()
print("python", sys.version.split()[0], "| cpus", os.cpu_count())
try:
    import rdkit  # noqa: F401
except ImportError:
    owner, slug = RDKIT_WHEEL_DATASET.split("/")
    wd = find_dataset(slug, owner)
    r = subprocess.run([sys.executable, "-m", "pip", "install", "--no-deps", "--no-index", "--quiet",
                        f"--find-links={wd}", "rdkit==2026.3.3"], capture_output=True, text=True)
    print("rdkit install", r.returncode, r.stderr[-500:])
CODE = find_dataset(CODE_DATASET, OWNER)
BUNDLE = find_dataset(BUNDLE_DATASET, OWNER)
NPDIR = find_dataset(NP_DATASET, OWNER)
print("code", CODE, "| bundle", BUNDLE, "| np", NPDIR)
assert CODE is not None and (CODE / "casmi" / "encoder.py").is_file(), "code dataset missing"
assert BUNDLE is not None and (BUNDLE / "info.json").is_file(), "bundle dataset missing"
NPFP = sorted(NPDIR.rglob("np_fp.npy"))[0]
sys.path.insert(0, str(CODE))
import torch
N_GPU = torch.cuda.device_count()
print("torch", torch.__version__, "cuda", torch.version.cuda, "gpus", N_GPU,
      [torch.cuda.get_device_name(i) for i in range(N_GPU)])
subprocess.run(["nvidia-smi"], check=False)
info = json.loads((BUNDLE / "info.json").read_text())
print("bundle:", {k: info.get(k) for k in ("created", "n_structures", "n_spectra", "n_groups",
                                            "holdout_sha256", "git_commit")})
OUT.mkdir(parents=True, exist_ok=True)
(OUT / "bundle_info.json").write_text(json.dumps(info, indent=1))
'''
    run = r'''
parallel = N_GPU >= len(ARMS)
hours = HOURS if parallel else HOURS / max(1, len(ARMS))
env0 = dict(os.environ, PYTHONPATH=str(CODE), CASMI_ROOT=str(WORK / "casmi_run"),
            NUMBA_CACHE_DIR=str(WORK / "numba_cache"), PYTHONUNBUFFERED="1")


def command(arm):
    cmd = [sys.executable, str(CODE / "scripts" / "train_encoder.py"), "--arm", arm,
           "--hours", str(hours), "--bundle", str(BUNDLE), "--np-fp", str(NPFP),
           "--out", str(OUT / arm), "--device", "cuda:0" if N_GPU else "cpu",
           "--eval-max-mol", str(EVAL_MAX_MOL)]
    for k, v in sorted(SETS.items()):
        cmd += ["--set", f"{k}={json.dumps(v)}"]
    return cmd


def launch(i, arm):
    (OUT / arm).mkdir(parents=True, exist_ok=True)
    env = dict(env0, CUDA_VISIBLE_DEVICES=str(i % max(N_GPU, 1)))
    fh = open(OUT / arm / "stdout.log", "w")
    print("launch", arm, "on gpu", env["CUDA_VISIBLE_DEVICES"], "hours", hours, flush=True)
    return subprocess.Popen(command(arm), env=env, stdout=fh, stderr=subprocess.STDOUT), fh


def tail(arm, n=2):
    p = OUT / arm / "stdout.log"
    try:
        lines = [l for l in p.read_text(errors="replace").splitlines() if "INFO" in l or "Error" in l]
    except OSError:
        return []
    return lines[-n:]


def wait(procs):
    last = 0.0
    while any(p.poll() is None for p, _, _ in procs):
        time.sleep(20)
        if time.time() - last > 600:
            last = time.time()
            for p, _, arm in procs:
                print(f"[{(time.time() - T0) / 60:.0f} min] {arm} rc={p.poll()}", *tail(arm), sep="\n  ",
                      flush=True)
    for p, fh, arm in procs:
        fh.close()
        print(arm, "exit code", p.returncode, flush=True)


if parallel:
    procs = []
    for i, arm in enumerate(ARMS):
        p, fh = launch(i, arm)
        procs.append((p, fh, arm))
    wait(procs)
else:
    for i, arm in enumerate(ARMS):
        p, fh = launch(0, arm)
        wait([(p, fh, arm)])
'''
    report = r'''
for arm in ARMS:
    print("=" * 30, arm)
    for l in tail(arm, 6):
        print(l)
    sp = OUT / arm / "summary.json"
    if sp.exists():
        s = json.loads(sp.read_text())
        print(json.dumps({k: s.get(k) for k in ("steps", "train_seconds", "wall_seconds", "n_params")}))
        print(json.dumps(s.get("final", {}), indent=1))
for p in sorted(OUT.rglob("*")):
    if p.is_file():
        print(f"{p.stat().st_size / 1e6:9.1f} MB  {p.relative_to(WORK)}")
print(f"total {(time.time() - T0) / 60:.1f} min")
'''
    return _nb([_md("# casmi encoder training (GPU)\nGenerated by `scripts/kaggle_encoder_kernel.py`."),
                _code(settings), _code(FIND_INPUT), _code(setup), _code(run), _code(report)])


def _commit() -> str:
    import subprocess

    try:
        return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short=12", "HEAD"],
                              capture_output=True, text=True, timeout=10).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def save_kernel(own: str, nb: dict, datasets: list[str], timeout_s: int, machine_shape: str | None
                ) -> dict:
    """``SaveKernel`` with GPU on and an optional machine shape (e.g. NvidiaTeslaT4 = T4 x2)."""
    text = json.loads(json.dumps(nb))
    for cell in text.get("cells", []):
        if cell.get("cell_type") == "code":
            cell["outputs"] = []
    body = {"slug": f"{own}/{SLUG}", "newTitle": TITLE, "text": json.dumps(text),
            "language": "python", "kernelType": "notebook", "isPrivate": True,
            "enableGpu": True, "enableTpu": False, "enableInternet": False,
            "datasetDataSources": datasets, "competitionDataSources": [], "kernelDataSources": [],
            "modelDataSources": [], "categoryIds": [], "sessionTimeoutSeconds": int(timeout_s)}
    if machine_shape:
        body["machineShape"] = machine_shape
    d = kc.rpc("kernels.KernelsApiService", "SaveKernel", body, timeout=300)
    problems = {k: d.get(k) for k in ("error", "invalidTags", "invalidDatasetSources",
                                       "invalidCompetitionSources", "invalidKernelSources") if d.get(k)}
    if problems:
        raise kc.KaggleError(f"SaveKernel: {problems}")
    return d


def fetch(own: str) -> Path:
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    dest = ROOT / "dist" / "kaggle" / "output" / f"{SLUG}_{stamp}"
    files = kc.kernel_output(own, SLUG, dest)
    kc.say(f"fetched {len(files)} files into {dest}")
    logp = dest / f"{SLUG}.log"
    if logp.exists():
        lines = kc.log_text_lines(logp.read_text())
        (dest / f"{SLUG}.txt").write_text("\n".join(lines) + "\n")
    return dest


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("cmd", choices=("notebook", "push", "status", "fetch"))
    p.add_argument("--arms", nargs="+", default=["bce", "focal_con"])
    p.add_argument("--hours", type=float, default=4.5)
    p.add_argument("--set", action="append", default=[], metavar="KEY=VALUE",
                   help="Config override for every arm (value parsed as JSON, else string)")
    p.add_argument("--eval-max-mol", type=int, default=0)
    p.add_argument("--owner", default=None)
    p.add_argument("--machine-shape", default="NvidiaTeslaT4", help="'' to let Kaggle choose")
    p.add_argument("--timeout-hours", type=float, default=None, help="session timeout (default hours + 1.5)")
    p.add_argument("--wait", action="store_true")
    p.add_argument("--fetch", action="store_true")
    args = p.parse_args(argv)
    own = kc.owner(args.owner)
    if args.cmd == "status":
        kc.say(str(kc.kernel_status(own, SLUG)))
        return 0
    if args.cmd == "fetch":
        fetch(own)
        return 0
    sets = {}
    for it in args.set:
        k, _, v = it.partition("=")
        try:
            sets[k] = json.loads(v)
        except ValueError:
            sets[k] = v
    nb = notebook(own, args.arms, args.hours, sets, args.eval_max_mol, _commit())
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    NOTEBOOK.write_text(json.dumps(nb, indent=1) + "\n")
    kc.say(f"wrote {NOTEBOOK}")
    if args.cmd == "notebook":
        return 0
    datasets = [f"{own}/{CODE_DATASET}", f"{own}/{BUNDLE_DATASET}", f"{own}/{NP_DATASET}",
                kc.RDKIT_WHEEL_DATASET]
    parallel_hours = args.hours if args.machine_shape else args.hours
    timeout = args.timeout_hours if args.timeout_hours else parallel_hours * (1 if args.machine_shape else len(args.arms)) + 1.5
    d = save_kernel(own, nb, datasets, int(timeout * 3600), args.machine_shape or None)
    kc.say(f"pushed /code/{own}/{SLUG} version {d.get('versionNumber')} (url {d.get('url')})")
    if args.wait:
        st = kc.wait_kernel(own, SLUG, timeout_s=timeout * 3600 + 1800, poll_s=60)
        kc.say(f"kernel finished: {st}")
        if args.fetch:
            fetch(own)
    return 0


if __name__ == "__main__":
    sys.exit(main())
